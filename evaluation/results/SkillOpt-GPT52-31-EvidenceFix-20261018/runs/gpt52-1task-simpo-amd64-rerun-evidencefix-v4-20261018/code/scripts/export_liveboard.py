def load_json(path: Path) -> dict[str, Any]:
    if not path.is_file():
        return {}
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception as exc:  # noqa: BLE001
        return {"error_category": "invalid_json", "error": repr(exc)}


def classify(result: dict[str, Any], path: Path) -> str:
    if not path.exists():
        return "pending"
    # Explicit bool pass/fail even if comparable is missing (imported baselines).
    if result.get("task_passed") is True:
        return "pass"
    if result.get("task_passed") is False:
        return "fail"
    if result.get("error_category"):
        return f"error:{result['error_category']}"
    if result.get("comparable") is False:
        return "non_comparable"
    if result.get("termination_reason") == "infrastructure_error":
        return "error:infrastructure_error"
    return "present"


def delta(baseline: str, method: str) -> str:
    if baseline == "pending" or method == "pending":
        return "pending"
    if baseline.startswith("error") or method.startswith("error"):
        return "error"
    if baseline == "fail" and method == "pass":
        return "fixed"
    if baseline == "pass" and method == "fail":
        return "regression"
    if baseline == method == "pass":
        return "kept_pass"
    if baseline == method == "fail":
        return "still_fail"
    return "other"


def build_suite_snapshot(suite: dict[str, Any]) -> dict[str, Any]:
    tasks = load_task_ids()
    baseline_run = suite["baseline_run_id"]
    arms_cfg = suite["arms"]

    baseline_status: dict[str, str] = {}
    for task_id in tasks:
        path = ROOT / "experiments" / baseline_run / "baseline" / "original-skill" / task_id / "benchmark_result.json"
        # Also accept symlink runs that point baseline at the same place.
        baseline_status[task_id] = classify(load_json(path), path)

    arm_summaries: list[dict[str, Any]] = []
    per_arm_status: dict[str, dict[str, str]] = {}

    for arm in arms_cfg:
        label = arm["label"]
        run_id = arm["run_id"]
        statuses: dict[str, str] = {}
        for task_id in tasks:
            # Prefer method result under the arm run; baseline may be symlinked.
            path = ROOT / "experiments" / run_id / "methods" / "skillopt" / task_id / "method_result.json"
            statuses[task_id] = classify(load_json(path), path)
        per_arm_status[label] = statuses

        deltas = {t: delta(baseline_status[t], statuses[t]) for t in tasks}
        arm_summaries.append(
            {
                "label": label,
                "run_id": run_id,
                "n": int(arm["n"]),
                "L": int(arm["L"]),
                "R": int(arm["R"]),
                "done": sum(1 for t in tasks if statuses[t] != "pending"),
                "pass": sum(1 for t in tasks if statuses[t] == "pass"),
                "fail": sum(1 for t in tasks if statuses[t] == "fail"),
                "fixed": sum(1 for t in tasks if deltas[t] == "fixed"),
                "regression": sum(1 for t in tasks if deltas[t] == "regression"),
                "pending": sum(1 for t in tasks if statuses[t] == "pending"),
            }
        )

    rows: list[dict[str, Any]] = []
    for task_id in tasks:
        rows.append(
            {
                "task_id": task_id,
                "baseline": baseline_status[task_id],
                "arms": [
                    {
                        "label": arm["label"],
                        "status": per_arm_status[arm["label"]][task_id],
                        "delta": delta(baseline_status[task_id], per_arm_status[arm["label"]][task_id]),
                    }
                    for arm in arms_cfg
                ],
            }
        )

    baseline_pass = sum(1 for t in tasks if baseline_status[t] == "pass")
    baseline_fail = sum(1 for t in tasks if baseline_status[t] == "fail")

    return {
        "generated_at": datetime.now().astimezone().isoformat(timespec="seconds"),
        "suite_id": suite.get("suite_id", "suite"),
        "title": suite.get("title", "SkillOpt hyperparam suite"),
        "provider": suite.get("provider", "tatu"),
        "baseline_model": suite.get("baseline_model", ""),
        "optimizer_model": suite.get("optimizer_model", ""),
        "baseline_run_id": baseline_run,
        "baseline_pass": baseline_pass,
        "baseline_fail": baseline_fail,
        "tasks": len(tasks),
        "arms": arm_summaries,
        "rows": rows,
    }


def build_legacy_snapshot(run_id: str) -> dict[str, Any]:
    """Single-run snapshot adapted into the suite-shaped canvas (one arm)."""
    run_root = ROOT / "experiments" / run_id
    meta = load_json(run_root / "metadata.json")
    suite = {
        "suite_id": f"legacy-{run_id}",
        "title": f"Legacy single run {run_id}",
        "baseline_run_id": run_id,
        "baseline_model": meta.get("baseline_model") or meta.get("benchmark_model") or "unknown",
        "optimizer_model": meta.get("optimizer_model") or "tatu/gpt-5.5@CODING_TATU",
        "provider": "tatu",
        "arms": [
            {
                "label": "skillopt",
                "run_id": run_id,
                "n": (meta.get("params") or {}).get("n", 3),
                "L": (meta.get("params") or {}).get("L", 4),
                "R": (meta.get("params") or {}).get("R", 2),
            }
        ],
    }
    return build_suite_snapshot(suite)


def render_canvas(snapshot: dict[str, Any]) -> str:
    data_json = json.dumps(snapshot, ensure_ascii=False, indent=2)
    return CANVAS_TEMPLATE.replace("__SNAPSHOT_JSON__", data_json)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--suite", type=Path, default=None, help="Multi-arm suite JSON")
    parser.add_argument("--run-id", default=None, help="Legacy single-run mode")
    parser.add_argument("--canvas", type=Path, default=CANVAS_PATH)
    args = parser.parse_args()

    if args.run_id:
        snapshot = build_legacy_snapshot(args.run_id)
        out_dir = ROOT / "experiments" / args.run_id / "liveboard"
    else:
        suite_path = args.suite or DEFAULT_SUITE
        if not suite_path.is_file():
            raise SystemExit(f"suite not found: {suite_path}")
        suite = json.loads(suite_path.read_text(encoding="utf-8"))
        snapshot = build_suite_snapshot(suite)
        out_dir = ROOT / "experiments" / "liveboards" / suite.get("suite_id", "suite")

    out_dir.mkdir(parents=True, exist_ok=True)
    snapshot_path = out_dir / "snapshot.json"
    snapshot_path.write_text(json.dumps(snapshot, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    args.canvas.parent.mkdir(parents=True, exist_ok=True)
    args.canvas.write_text(render_canvas(snapshot), encoding="utf-8")

    print(f"suite_id={snapshot.get('suite_id')}")
    print(f"snapshot={snapshot_path}")
    print(f"canvas={args.canvas}")
    print(f"baseline_pass={snapshot['baseline_pass']}/{snapshot['tasks']}")
    for arm in snapshot["arms"]:
        print(
            f"  {arm['label']}: done={arm['done']}/{snapshot['tasks']} "
            f"pass={arm['pass']} rescue={arm['fixed']} regress={arm['regression']} "
            f"pending={arm['pending']} run={arm['run_id']}"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
